#!/usr/bin/env node
/**
 * Build script: Scans public/docs for PDF files and generates a TypeScript module.
 * Run before dev/build so the app uses the actual files in public/docs.
 *
 * Usage: node scripts/generate-documents.js
 * Or: npm run generate-documents
 */

const fs = require('fs');
const path = require('path');

const DOCS_DIR = path.join(process.cwd(), 'public', 'docs');
const OUTPUT_FILE = path.join(process.cwd(), 'src', 'generated', 'documents.ts');

/**
 * Generate document ID from filename (matches apiService transformObligationToSnippet)
 * Format: doc-${name.toLowerCase().replace(/[^a-z0-9]+/g, '-')}
 */
function generateDocumentId(fileName) {
  const nameWithoutExt = fileName.replace(/\.pdf$/i, '');
  const slug = nameWithoutExt.toLowerCase().replace(/[^a-z0-9]+/g, '-');
  return `doc-${slug}-pdf`;
}

function main() {
  // Ensure docs directory exists
  if (!fs.existsSync(DOCS_DIR)) {
    console.warn(`[generate-documents] Directory not found: ${DOCS_DIR}`);
    fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
    fs.writeFileSync(
      OUTPUT_FILE,
      `// Auto-generated - no PDFs in public/docs
// Run: npm run generate-documents

export interface GeneratedDocument {
  id: string;
  name: string;
  uploadDate: string;
  uploadedBy: string;
  totalPages: number;
}

export const DOCUMENTS: GeneratedDocument[] = [];
export const ALL_DOCUMENTS: Array<{ id: string; name: string }> = [];
`,
      'utf8'
    );
    console.log('[generate-documents] No docs folder - wrote empty module');
    return;
  }

  const entries = fs.readdirSync(DOCS_DIR, { withFileTypes: true });
  const pdfFiles = entries
    .filter((e) => e.isFile() && /\.pdf$/i.test(e.name))
    .map((e) => e.name)
    .sort();

  if (pdfFiles.length === 0) {
    console.warn('[generate-documents] No PDF files found in public/docs');
  }

  const today = new Date().toISOString().split('T')[0].replace(/-/g, '/');
  const documents = pdfFiles.map((fileName) => {
    const id = generateDocumentId(fileName);
    return {
      id,
      name: fileName,
      uploadDate: today,
      uploadedBy: 'system',
      totalPages: 0,
    };
  });

  const allDocuments = documents.map((d) => ({ id: d.id, name: d.name }));

  const tsContent = `// AUTO-GENERATED - Do not edit manually
// Source: public/docs/*.pdf
// Generated by: scripts/generate-documents.js
// Run before dev/build: npm run generate-documents

export interface GeneratedDocument {
  id: string;
  name: string;
  uploadDate: string;
  uploadedBy: string;
  totalPages: number;
}

export const DOCUMENTS: GeneratedDocument[] = ${JSON.stringify(documents, null, 2)};

/** Simplified list for AgreementPreview Documents tab */
export const ALL_DOCUMENTS: Array<{ id: string; name: string }> = ${JSON.stringify(allDocuments, null, 2)};
`;

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true });
  fs.writeFileSync(OUTPUT_FILE, tsContent, 'utf8');
  console.log(`[generate-documents] Wrote ${documents.length} document(s) to ${OUTPUT_FILE}`);
}

main();
